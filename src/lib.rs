//! # 🦀 `ar` — آزمایشگاه کامل Rust در قالب یک برنامهٔ واقعی
//!
//! این کریت هم **کتابخانه** است (تا تست‌ها و doctestها بتوانند از آن استفاده کنند)
//! و هم یک **برنامهٔ اجرایی** (فایل `src/main.rs`).
//!
//! ## این پروژه چیست؟
//! یک مدیر کار (task manager) کامل با:
//! * خط فرمان با فلگ‌های واقعی (`--priority`, `--tags`, `--json` …)
//! * ذخیره‌سازی روی دیسک با قالب JSON که **خودمان** نوشتیم
//! * آمار و جدول‌سازی زیبا در ترمینال
//! * و به‌زودی: سرور HTTP، اجراکنندهٔ async و دموی همهٔ مفاهیم زبان
//!
//! ## چرا این پروژه برای یادگیری خوب است؟
//! چون **صفر وابستگی** است. هر خط کد را می‌فهمی؛ هیچ جادویی از یک crate بیرونی
//! وجود ندارد. این ماژول‌ها را به این ترتیب بخوان:
//!
//! | ترتیب | ماژول | چه چیزی یاد می‌گیری |
//! |-------|-------|---------------------|
//! | ۱ | [`model`] | struct، enum، derive، newtype، `Display` و `FromStr` |
//! | ۲ | [`errors`] | `Result`، `?`، `From`، زنجیرهٔ علت خطا |
//! | ۳ | [`json`] | enum با داده، بازگشت، پارسر، بایت در مقابل کاراکتر |
//! | ۴ | [`store`] | صفت (trait)، `dyn`، `RefCell`، نوشتن اتمیک فایل |
//! | ۵ | [`app`] | ایتراتورها، بستارها، `BTreeMap`/`HashMap`، الگوی `entry` |
//! | ۶ | [`cli`] | `env::args`، ایتراتور، ژنریک با `FromStr` |
//! | ۷ | [`table`] | فرمت‌کردن، عرض یونیکد، ماکروی `write!` |
//! | ۸ | [`color`] | ANSI، `static` و اتمیک، احترام به `NO_COLOR` |
//!
//! سپس در `src/demos/` دموهای جداگانه‌ای برای هر مفهوم هست و با
//! `cargo run -- demo <topic>` می‌توانی همه را ببینی.
//!
//! ## راهنمای مستندات
//! پوشهٔ `docs/` یک مرجع فارسی کامل و ریزبه‌ریز است؛ از `docs/00-roadmap.md` شروع کن.

