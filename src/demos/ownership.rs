mod tests {
    use super::*;

    #[test]
    fn demo_runs_without_panic() {
        run();
    }

    #[test]
    fn first_word_returns_borrow_of_input() {
        let s = String::from("سلام دنیا");
        assert_eq!(first_word(&s), "سلام");
        assert_eq!(str_len("سلام"), 4); // ۴ کاراکتر، ۸ بایت
        assert_eq!("سلام".len(), 8);    // ← تفاوت بایت و کاراکتر
    }

    #[test]
    fn mem_take_and_replace() {
        let mut o = Some(1);
        assert_eq!(o.take(), Some(1));
        assert_eq!(o, None);
    }
}
