/// نام و نسخهٔ این کریت (از `Cargo.toml` خوانده می‌شود).
///
/// 🌟 `env!` یک **ماکروی زمان کامپایل** است: مقدار در فایل اجرایی «حک» می‌شود
/// (چیزی شبیه `#define` در C ولی تایپ‌سِیف). نسخهٔ `option_env!` هم هست که
/// به‌جای خطا، `Option` می‌دهد.
pub const NAME: &str = env!("CARGO_PKG_NAME");
/// نسخهٔ پروژه
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// یک خط توضیح برای `ar version`.
pub fn version_line() -> String {
    format!("{NAME} {VERSION} (ساخته‌شده با Rust {})", rustc_version())
}

/// نسخهٔ کامپایلر — ترفند رایج در کریت‌ها برای نمایش اطلاعات ساخت.
pub fn rustc_version() -> &'static str {
    // این متغیرها را cargo هنگام کامپایل ست می‌کند
    option_env!("RUSTC_VERSION").unwrap_or("؟")
}
