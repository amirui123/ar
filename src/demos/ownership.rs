//! # دموی مالکیت (Ownership) — مهم‌ترین مفهوم Rust
//!
//! سه قانون طلایی:
//! 1. هر مقدار یک **مالک** دارد.
//! 2. در هر لحظه فقط **یک** مالک.
//! 3. وقتی مالک از دامنه بیرون رفت، مقدار **رها** (drop) می‌شود.
//!
//! و قانون قرض‌گیری: در هر لحظه یا **یک قرض تغییرپذیر**، یا **هر تعداد قرض ثابت**.

use crate::color;

/// اجرای دمو.
pub fn run() {
    println!("{}", color::bold("۱) انتقال (move) و کپی (copy)"));
    move_vs_copy();

    println!("\n{}", color::bold("۲) قرض‌گیری (borrow) — قرض بدون انتقال مالکیت"));
    borrowing();

    println!("\n{}", color::bold("۳) قرض تغییرپذیر — فقط یکی در هر زمان"));
    mutable_borrow();

    println!("\n{}", color::bold("۴) رها کردن (Drop) و ترتیب آن"));
    drop_order();

    println!("\n{}", color::bold("۵) چگونه از دعوا فرار کنیم؟ clone، Rc، یا بازطراحی"));
    avoid_the_fight();
}

// ═══════════════════════════════════════════════════════════════════════════
fn move_vs_copy() {
    // String روی «پشته» (heap) زندگی می‌کند: سه کلمه روی استک (اشاره‌گر، طول، ظرفیت)
    // و بایت‌های واقعی روی heap. پس کپی «سطحی» خطرناک است → Rust انتقال می‌دهد.
    let a = String::from("سلام");
    let b = a; // ⬅️ مالکیت منتقل شد؛ از این به بعد `a` دیگر معتبر نیست
    // println!("{a}");  // ← اگر این را از کامنت دربیاوری، خطای کامپایل می‌گیری:
    //                   //   error[E0382]: borrow of moved value: `a`
    println!("  String منتقل شد (move) → b = {b}");

    // ولی انواع ساده (Scalar) کپی می‌شوند، چون «کپی‌کردن» آن‌ها رایگان است.
    // این نوع‌ها صفت Copy را پیاده می‌کنند.
    let x: i32 = 5;
    let y = x; // کپی، نه انتقال
    println!("  i32 کپی شد (copy) → x={x} و y={y} هر دو زنده‌اند");

    // 🔑 ترفند: می‌توانی بپرسی آیا یک نوع Copy است یا نه — در زمان کامپایل:
    fn is_copy<T: Copy>() -> bool {
        true // اگر این تابع کامپایل شد، یعنی T: Copy بوده
    }
    println!("  String کپی‌شدنی است؟ {}", false);
    println!("  i32 کپی‌شدنی است؟ {}", is_copy::<i32>());
    // is_copy::<String>()  ← این خط کامپایل نمی‌شود؛ همین‌جا خطا گرفته‌ایم، نه در تست!

    // نسخهٔ «مرجع‌دار»: انتقال به تابع
    takes_ownership(a_string());
    // ببین: تابع زیر مالکیت را می‌گیرد و *برنمی‌گرداند* → مقدار در پایان تابع رها می‌شود
}

/// این تابع مالکیت `String` را می‌گیرد (پس فراخوانی‌کننده دیگر نمی‌تواند استفاده کند).
fn takes_ownership(s: String) {
    println!("  تابع مالکیت را گرفت: «{s}» (حالا رها می‌شود)");
}

fn a_string() -> String {
    String::from("هدیه")
}

// ═══════════════════════════════════════════════════════════════════════════
fn borrowing() {
    let owned = String::from("کتاب Rust");

    // &owned یک «قرض ثابت» (immutable reference) است — مالکیت نمی‌رود.
    let len = str_len(&owned);
    println!("  طول «{owned}» = {len} (ولی هنوز مالک خودمانیم)");

    // می‌توان چند قرض ثابت هم‌زمان داشت — چون هیچ‌کس تغییری نمی‌دهد.
    let r1 = &owned;
    let r2 = &owned;
    println!("  دو قرض هم‌زمان: «{r1}» و «{r2}»");

    // ترفند: تابع می‌تواند برش (slice) بگیرد — بدون هیچ کپی
    let first_word = first_word(&owned);
    println!("  اولین کلمه: «{first_word}» (برشی از خود رشته، صفر کپی)");
}

/// `&str` یعنی «قرضِ یک رشته» — تابع مالک نمی‌شود.
fn str_len(s: &str) -> usize {
    s.chars().count() // برای متن یونیکد، کاراکتر بشمار نه بایت!
}

/// برگرداندن برش از ورودی — **نکتهٔ عمر:**
/// خروجی `&str` است و باید بدانیم به کدام ورودی وابسته است.
/// کامپایلر خودش با قاعدهٔ «حذف عمر» (lifetime elision) خروجی را به همان
/// ورودی تک‌مرجع گره می‌زند: تا وقتی ورودی زنده است، خروجی هم معتبر است.
fn first_word(s: &str) -> &str {
    match s.split_whitespace().next() {
        Some(w) => w,
        None => s,
    }
}

// ═══════════════════════════════════════════════════════════════════════════
fn mutable_borrow() {
    let mut counter = 0;
    increment(&mut counter); // «قرض تغییرپذیر»
    increment(&mut counter);
    println!("  شمارنده بعد از دو بار افزایش: {counter}");

    // ⚠️ قاعدهٔ طلایی: در هر لحظه *فقط یک* قرض تغییرپذیر،
    // و اگر قرض تغییرپذیر داری، هیچ قرض ثابتی هم نمی‌شود داشت.
    let mut data = vec![3, 1, 2];
    data.sort(); // اینجا یک قرض تغییرپذیر کوتاه‌مدت گرفته و آزاد شده
    println!("  بردار مرتب‌شده: {data:?}");

    // دامنهٔ قرض‌ها (NLL) با آخرین *استفاده* تمام می‌شود، نه با انتهای بلوک:
    let r = &data; // قرض ثابت شروع
    println!("  طول بردار: {}", r.len()); // آخرین استفاده از r اینجاست
    data.push(4); // ✅ مجاز: قرض r دیگر زنده نیست (Non-Lexical Lifetimes)
    println!("  بعد از افزودن: {data:?}");
}

/// `&mut i32` — قرض تغییرپذیر. توجه: بدون `mut` در امضا، نمی‌توان تغییر داد.
fn increment(n: &mut i32) {
    *n += 1; // `*` برای «درآیند کردن» (dereference) اشاره‌گر
}

// ═══════════════════════════════════════════════════════════════════════════
fn drop_order() {
    // ساختار زیر هر تسک را چاپ می‌کند تا ببینی ترتیب رها شدن چطور است.
    struct Loud(&'static str);

    impl Drop for Loud {
        fn drop(&mut self) {
            println!("  رها شد: {}", self.0);
        }
    }

    // متغیرها به **عکس ترتیب ساخت** رها می‌شوند (مثل پشته).
    let _first = Loud("اول (دیرتر رها می‌شود)");
    let _second = Loud("دوم (زودتر رها می‌شود)");
    println!("  (اینجا هر دو زنده‌اند)");

    // ترفند: `drop(x)` مقدار را همین حالا و به‌صورت دستی رها می‌کند.
    let manual = Loud("سوم (با drop دستی)");
    drop(manual);
    println!("  بعد از drop دستی");

    // نکتهٔ ریز: `_` مقدار را فوراً رها می‌کند، ولی `_name` تا انتهای بلوک می‌ماند!
    let _ = Loud("چهارم (با _ فوراً رها شد)");
    let _kept = Loud("پنجم (با نام، تا آخر بلوک)");
    println!("  پایان بدنهٔ تابع: از اینجا به بعد به ترتیب رها می‌شوند ↑");
}

// ═══════════════════════════════════════════════════════════════════════════
fn avoid_the_fight() {
    // راه ۱: «بازطراحی» — به‌جای نگه‌داشتن مرجع، داده را در ساختار نگه دار.
    // راه ۲: شاخص به‌جای مرجع (مثل کاری که در app.rs با TaskId کردیم).
    // راه ۳: Rc/Arc برای مالکیت مشترک (دموی smart_pointers).
    let names = vec!["زهرا".to_string(), "علی".to_string()];

    // گلولهٔ نقرهای: ایتراتورها اجازه می‌دهند داده را «قرض» ببینی و بدون
    // درگیری با مالکیت، کار کنی.
    for n in &names {
        println!("  نام: {n}");
    }

    let total_len: usize = names.iter().map(|n| n.chars().count()).sum();
    println!("  مجموع طول نام‌ها: {total_len}");

    // ترفند ریز: `std::mem::take` مقدار را «برمی‌دارد» و جای آن پیش‌فرض می‌گذارد.
    let mut opt = Some(String::from("مقدار"));
    let taken = opt.take();
    println!("  take: {:?} (جای قبلی: {:?})", taken, opt);

    // و `std::mem::replace` که مقدار جدید می‌گذارد و قدیمی را برمی‌گرداند.
    let mut s = String::from("قدیمی");
    let old = std::mem::replace(&mut s, String::from("جدید"));
    println!("  replace: «{old}» → «{s}»");
}

