#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
#  بالا آوردن رابط وب «ar» با ترمیم خودکارِ مقدمات 🩺
# ═══════════════════════════════════════════════════════════════════════════
#
#  چرا این اسکریپت؟ چون در محیط‌های موقت (sandbox / CI / کانتینر تازه) این‌ها
#  بعد از هر ری‌استارت پاک می‌شوند ولی **کد پروژه** می‌ماند:
#
#     ✗ ~/.cache/rust   → تول‌چین Rust (اگر با npm نصب شده باشد)
#     ✗ target/         → خروجی کامپایل (در .gitignore است)
#     ✗ data/           → دادهٔ زمان اجرا (اگر پاک شود، `seed` بازش می‌سازد)
#
#  پس این اسکریپت هر بار از صفر این‌ها را چک و در صورت نیاز درست می‌کند:
#
#     ۱) تول‌چین موجود است؟   وگرنه scripts/setup-rust.sh را صدا می‌زند
#     ۲) باینری ساخته شده؟    وگرنه cargo build
#     ۳) فایل داده هست؟       وگرنه ar seed (پنج تسک نمونه که موضوعشان خودِ Rust است)
#     ۴) سرور روی 0.0.0.0     تا از بیرون (proxied preview) هم دیده شود
#
#  استفاده:
#      bash scripts/run-web.sh                 # پیش‌فرض: 0.0.0.0:8080
#      PORT=9000 bash scripts/run-web.sh
#      FORCE_BUILD=1 bash scripts/run-web.sh   # حتی اگر باینری هست، دوباره بساز
# ═══════════════════════════════════════════════════════════════════════════
set -euo pipefail

PORT="${PORT:-8080}"
HOST="${HOST:-0.0.0.0}"           # ⚠️ مهم: 127.0.0.1 نگذار؛ پیش‌نمایش از بیرون وصل می‌شود
PREFIX="${PREFIX:-$HOME/.cache/rust}"
DATA="${DATA:-data/tasks.json}"

# ریشهٔ پروژه را از محل خودِ اسکریپت حساب می‌کنیم تا از هر جایی قابل اجرا باشد.
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# ── ۱) تول‌چین ───────────────────────────────────────────────────────────
if [ ! -x "$PREFIX/bin/cargo" ]; then
  echo "▸ تول‌چین Rust در «$PREFIX» نبود → نصب از npm (بدون rustup) ..."
  bash scripts/setup-rust.sh
fi
export PATH="$PREFIX/bin:$PATH"

# ── ۲) ساخت ──────────────────────────────────────────────────────────────
if [ ! -x target/debug/ar ] || [ -n "${FORCE_BUILD:-}" ]; then
  echo "▸ باینری نبود (یا FORCE_BUILD) → cargo build ..."
  cargo build            # پروفایل dev این پروژه خودش بهینه است (opt-level=2)
fi

# ── ۳) داده ──────────────────────────────────────────────────────────────
# `-s` = «هست و خالی نیست». خالی‌بودن = بار اول یا بعد از ری‌استارت.
if [ ! -s "$DATA" ]; then
  echo "▸ فایل داده «$DATA» خالی/ناموجود بود → ساخت نمونه ..."
  ./target/debug/ar --data "$DATA" --no-color seed
fi

# ── ۴) اجرا ──────────────────────────────────────────────────────────────
echo "▸ اجرا: http://$HOST:$PORT   (خروج: Ctrl+C)"
# `exec` یعنی همین پروسه جایگزین اسکریپت می‌شود → سیگنال‌ها (Ctrl+C) درست می‌رسند
# و پروسهٔ اضافه‌ای باقی نمی‌ماند. ترفند کوچک ولی درست برای اسکریپت‌های اجرا.
exec ./target/debug/ar serve --host "$HOST" --port "$PORT" --data "$DATA" --no-color
